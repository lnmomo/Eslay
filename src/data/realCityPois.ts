export const getRealCityPois = (city: string): RealCityPoi[] => {
  const key = seededCityPois[city] ? city : aliases[city] ?? city;
  return (seededCityPois[key] ?? []).map((seed, index) => ({
    ...seed,
    id: `${key.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-real-poi-${index + 1}`,
    city: key,
  }));
};

const distanceKm = (from: { latitude: number; longitude: number }, to: { latitude: number; longitude: number }) => {
  const earthRadiusKm = 6371;
  const dLat = ((to.latitude - from.latitude) * Math.PI) / 180;
  const dLng = ((to.longitude - from.longitude) * Math.PI) / 180;
  const lat1 = (from.latitude * Math.PI) / 180;
  const lat2 = (to.latitude * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) * Math.sin(dLng / 2);
  return earthRadiusKm * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
};

